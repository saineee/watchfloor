#!/usr/bin/env bash
set -euo pipefail

usage() {
  cat <<EOF
Usage:
  API=<base-url> ./gen_traffic.sh

Generates synthetic network alerts and sends them to the API.
By default, traffic is sent to a local uvicorn server at:
  http://localhost:8000

Configuration:
  This script requires scripts/.env.traffic to exist and define:
  WF_EMAIL      Email address used to register/login to the API.
  WF_PASSWORD   Password used to register/login to the API.

  The .env.traffic file is intended for local/script configuration and should not
  be committed to GitHub or your choice of version control. Add it to .gitignore.

Environment:
  API
    Optional. Base URL of the API that will receive the generated alerts.
    Defaults to http://localhost:8000.

  COUNT
    Optional. Number of synthetic alerts to generate.
    Defaults to 20.

Examples:
  # Send 20 synthetic alerts to a local API
  API=http://localhost:8000 ./gen_traffic.sh

  # Generate 10 synthetic alerts
  COUNT=10 ./gen_traffic.sh

  # Send 50 synthetic alerts to a configured API endpoint
  API=http://10.0.0.100 COUNT=50 ./gen_traffic.sh

Each alert is generated with a random device and error type
and submitted using HTTP POST /alerts.
EOF
}

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
  usage
  exit 0
fi

ENV_FILE="$(dirname "$0")/.env.traffic"
if [[ ! -f "$ENV_FILE" ]]; then
  echo "Error: $ENV_FILE not found." >&2
  echo "Define WF_EMAIL and WF_PASSWORD before running this script." >&2
  exit 1
fi

# shellcheck source=/dev/null
source "$ENV_FILE"

: "${WF_PASSWORD:?WF_PASSWORD not set in scripts/.env.traffic}"
: "${WF_EMAIL:?WF_EMAIL not set in scripts/.env.traffic}"
API="${API:-http://localhost:8000}"

if [[ ! "$API" =~ ^https?:// ]]; then
  echo "API must start with https://" >&2
  exit 1
fi
if [[ "$API" =~ ^http:// ]] && ! [[ "$API" =~ ^http://localhost(:[0-9]+)?$ ]] ; then
  echo "API must start with http://localhost, or use https:// for CloudFront. http://<ALB hostname> does not work due to the session cookie being Secure, so it cannot be sent over http." >&2
  exit 1
fi

COUNT="${COUNT:-20}"

devices=(core-sw-01 edge-fw-02 nas-backup-01 dist-sw-01 dns-srv-02)
errors=(interface_down disk_usage_high tunnel_flap packet_loss_high service_down)

JAR="$(mktemp)"

trap 'rm -f "$JAR"' EXIT

declare -A states=(
  [interface_down]=down
  [service_down]=down
  [disk_usage_high]=up
  [tunnel_flap]=degraded
  [packet_loss_high]=degraded
  )

body="$(jq -n --arg email "$WF_EMAIL" --arg password "$WF_PASSWORD" '{email: $email, password: $password}')"

register_code="$(curl -s -o /dev/null -w  "%{http_code}" -H "Content-Type: application/json" -d "$body" "$API/auth/register")"

if [[ "$register_code" != "201" && "$register_code" != "409" ]]; then
  echo 'Unable to create user' >&2
  exit 1
fi

login_code="$(curl -c "$JAR" -s -o /dev/null -w "%{http_code}" -H "Content-Type: application/json" -d "$body" "$API/auth/login")"
if [[ "$login_code" != "200" ]]; then
  echo 'Unable to login' >&2
  exit 1
fi

for ((i = 1; i <= COUNT; i++)); do
  device="${devices[RANDOM % ${#devices[@]}]}"
  error="${errors[RANDOM % ${#errors[@]}]}"
  device_state=${states[$error]}

  bodytemp="$(jq -n --arg device_name "$device" --arg error_type "$error" --arg device_state "$device_state" '{device_name: $device_name, error_type: $error_type, ip_address: "10.0.0.1", device_state: $device_state, description: "Synthetic alert generated by gen_traffic"}')"

  alert_code="$(curl -b "$JAR" -d "$bodytemp" -s -o /dev/null -w "%{http_code}" -H "Content-Type: application/json" "$API/alerts")"

  echo "[$i/$COUNT] $device $error -> $alert_code"

  if [[ "$alert_code" != "200" && "$alert_code" != "201" ]]; then
    echo "API Error or Unexpected Response [$i/$COUNT]" >&2
  fi
  sleep 1
done
